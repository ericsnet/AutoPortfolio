/**
 * Deployment targets.
 *
 * The generator produces the same static site for every host; a target only
 * adds the handful of files that make a host behave well — `.nojekyll` for
 * GitHub Pages, cache headers for Netlify, `vercel.json`, and so on. Nothing
 * here changes the HTML, which is why a site can be moved between hosts later
 * without regenerating it.
 *
 * @module export/targets
 */

import path from 'node:path';
import { ErrorCodes, diagnostic } from '../util/errors.js';
import { isFile, readTextOrNull } from '../util/fsx.js';

/** @typedef {import('../util/errors.js').Diagnostic} Diagnostic */

/**
 * @typedef {object} ExportFile
 * @property {string} file     Path relative to the output directory.
 * @property {string} content
 * @property {string} reason   Shown in the build report.
 */

/**
 * @typedef {object} ExportNotes
 * @property {string} [summary]
 * @property {string[]} [steps]
 */

/**
 * @typedef {object} ExportContext
 * @property {any} project
 * @property {string} baseUrl
 * @property {string} basePath  Sub-path the site is served from (`''` for a root domain).
 * @property {string} output
 * @property {(file: string) => Promise<string|null>} readAsset Reads a file from the generated site.
 */

/**
 * @typedef {object} ExportTarget
 * @property {string} id
 * @property {string} label
 * @property {string} description
 * @property {string} docs
 * @property {(context: ExportContext) => ExportFile[]} files
 * @property {(context: ExportContext) => ExportNotes} notes
 */

const SECURITY_HEADERS = `/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: SAMEORIGIN
`;

const CACHE_HEADERS = `/assets/*
  Cache-Control: public, max-age=31536000, immutable
`;

/**
 * @param {string} basePath
 * @param {string} from
 * @param {string} to
 * @returns {string}
 */
function relativeRedirect(basePath, from, to) {
  const prefix = basePath ? basePath.replace(/\/$/, '') : '';
  return `${prefix}${from} ${prefix}${to}`;
}

