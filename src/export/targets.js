/** @type {ExportTarget} */
const githubPagesTarget = {
  id: 'github-pages',
  label: 'GitHub Pages',
  description: 'Adds `.nojekyll` (so folders starting with `_` are served) and an optional `CNAME`.',
  docs: 'https://docs.github.com/pages',
  files({ baseUrl }) {
    /** @type {ExportFile[]} */
    const files = [
      { file: '.nojekyll', content: '', reason: 'Stops Pages from running Jekyll over the output.' },
    ];
    const host = hostnameFor(baseUrl);
    if (host && !host.endsWith('github.io')) {
      files.push({
        file: 'CNAME',
        content: `${host}\n`,
        reason: 'Custom domain, taken from `site.baseUrl`.',
      });
    }
    return files;
  },
  notes({ baseUrl }) {
    return {
      summary: 'Publish the output directory to the `gh-pages` branch, or use the included GitHub Actions workflow.',
      steps: [
        'Run `autoportfolio init --ci` to scaffold a Pages workflow if this project does not have one.',
        baseUrl
          ? `Set the Pages custom domain to ${hostnameFor(baseUrl) ?? baseUrl} if you use one.`
          : 'Set `site.baseUrl` to your Pages URL, e.g. `https://you.github.io/your-repo`.',
      ],
    };
  },
};

