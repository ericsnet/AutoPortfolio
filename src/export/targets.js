/** @type {Record<string, ExportTarget>} */
export const EXPORT_TARGETS = {
  static: staticTarget,
  'github-pages': githubPagesTarget,
  netlify: netlifyTarget,
  vercel: vercelTarget,
  'cloudflare-pages': cloudflarePagesTarget,
  s3: s3Target,
  ipfs: ipfsTarget,
};

/** @param {string} name @returns {ExportTarget|null} */
export function getExportTarget(name) {
  if (!name) return null;
  const key = String(name).trim().toLowerCase();
  if (EXPORT_TARGETS[key]) return EXPORT_TARGETS[key];
  const aliases = {
    gh: 'github-pages',
    github: 'github-pages',
    pages: 'github-pages',
    cf: 'cloudflare-pages',
    cloudflare: 'cloudflare-pages',
    aws: 's3',
    amazon: 's3',
  };
  return EXPORT_TARGETS[aliases[key] ?? ''] ?? null;
}

/** Every target name, for `--help` and validation. */
export const EXPORT_TARGET_NAMES = Object.freeze(Object.keys(EXPORT_TARGETS));

/**
 * Apply a deployment target to a generated site.
 *
 * @param {object} options
 * @param {any} options.project      Loaded project.
 * @param {string} options.outDir    Output directory (absolute).
 * @param {string} [options.target]  Target id; falls back to the configuration.
 * @returns {Promise<{target: string, files: ExportFile[], notes: ExportNotes, diagnostics: Diagnostic[]}>}
 */
export async function applyExportTarget(options) {
  const { project, outDir } = options;
  const requested = options.target ?? project.config.deploy?.target ?? 'static';
  const target = getExportTarget(requested);
  /** @type {Diagnostic[]} */
  const diagnostics = [];

  if (!target) {
    return {
      target: String(requested),
      files: [],
      notes: {},
      diagnostics: [
        diagnostic({
          severity: 'error',
          code: ErrorCodes.EXPORT_UNKNOWN_TARGET,
          message: `Unknown deployment target \`${requested}\``,
          path: 'deploy.target',
          hint: `Available targets: ${EXPORT_TARGET_NAMES.join(', ')}.`,
        }),
      ],
    };
  }

  const baseUrl = project.config.site?.baseUrl ?? project.data.meta?.siteUrl ?? '';
  const basePath = normalizeBasePath(project.config.deploy?.basePath ?? baseUrl);

  const context = /** @type {ExportContext} */ ({
    project,
    baseUrl,
    basePath,
    output: path.relative(project.root, outDir) || '.',
    readAsset: (file) => readTextOrNull(path.join(outDir, file)),
  });

  const files = target.files(context).filter((file) => file.content !== undefined);

  // Extra files listed in `deploy.files` are copied verbatim from the project.
  for (const extra of project.config.deploy?.files ?? []) {
    const from = path.resolve(project.root, extra);
    if (!(await isFile(from))) {
      diagnostics.push(
        diagnostic({
          severity: 'warning',
          code: ErrorCodes.EXPORT_FAILED,
          message: `\`deploy.files\` lists \`${extra}\` but it does not exist`,
          path: 'deploy.files',
          hint: 'Paths are relative to the configuration file.',
        }),
      );
      continue;
    }
    const content = await readTextOrNull(from);
    if (content === null) continue;
    files.push({ file: path.basename(extra), content, reason: 'Listed in `deploy.files`.' });
  }

  return { target: target.id, files, notes: target.notes(context), diagnostics };
}

/**
 * The sub-path a site is served from, derived from the configuration or the
 * deployed URL (`https://example.com/portfolio/` -> `/portfolio`).
 *
 * @param {string} value
 * @returns {string}
 */
export function normalizeBasePath(value) {
  if (!value) return '';
  let pathname = '';
  try {
    if (/^https?:/i.test(value)) pathname = new URL(value).pathname;
    else pathname = value;
  } catch {
    pathname = value;
  }
  if (!pathname || pathname === '/') return '';
  const trimmed = pathname.replace(/\/+$/, '');
  return trimmed.startsWith('/') ? trimmed : `/${trimmed}`;
}

/**
 * @param {string} url
 * @returns {string|null}
 */
function hostnameFor(url) {
  if (!url) return null;
  try {
    return new URL(url).hostname;
  } catch {
    return null;
  }
}
